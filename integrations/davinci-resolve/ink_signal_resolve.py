"""Ink & Signal — DaVinci Resolve adapter (Resolve scripting API, Python 3).

Assembles an Ink & Signal NLE package into a Resolve timeline:
  V1 picture (your clips + full-frame comps) · V2 overlays (ProRes 4444 alpha) · V3 transitions
  A1 clip audio · A2 music · timeline markers from the plan.

Make the package first:   node render/nle.mjs plan.json --out pkg
No-script route:          File › Import › Timeline… › pkg/timeline.xml (FCP7 XML)
Scripted / MCP route (any Resolve MCP with "execute python"):
    import importlib.util
    spec = importlib.util.spec_from_file_location("ink_signal_resolve", "/abs/ink-signal/integrations/davinci-resolve/ink_signal_resolve.py")
    isr = importlib.util.module_from_spec(spec); spec.loader.exec_module(isr)
    isr.assemble("/abs/pkg")             # isr.use_resolve(resolve) first if the host hands you a `resolve` object
From a terminal (Resolve running, Preferences › System › General › External scripting = Local):
    python3 ink_signal_resolve.py /abs/path/pkg

Also: add_title(...) inserts a native, editable Fusion Text+ title styled with Ink & Signal tokens (beta).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__)) if "__file__" in globals() else os.environ.get("INK_SIGNAL_ROOT", os.getcwd())


def _load_tokens():
    for base in (HERE, os.path.join(HERE, "integrations", "davinci-resolve")):
        if os.path.exists(os.path.join(base, "ink_signal_tokens.py")):
            sys.path.insert(0, base)
            from ink_signal_tokens import TOKENS as t  # generated by tools/build.py
            return t
    for cand in (os.path.join(HERE, "..", "..", "tokens", "ink-signal.tokens.json"), os.path.join(HERE, "tokens", "ink-signal.tokens.json")):
        if os.path.exists(cand):
            return json.load(open(cand))
    # exec()'d from elsewhere with no library path: the few tokens add_title() needs
    return {"color": {"ink": "#0E0E0E", "paper": "#ECEBE6", "signal": "#F2362B", "pen": "#2B44E0", "white": "#FFFFFF"},
            "font": {"display": {"family": "Archivo Expanded", "style": "Black", "tracking": -0.01, "case": "upper"},
                     "label": {"family": "Archivo Expanded", "style": "ExtraBold", "tracking": 0.02, "case": "upper"},
                     "note": {"family": "Caveat", "style": "Bold", "tracking": 0, "case": "lower"}},
            "ease": {"snap": {"bezier": [0.16, 1, 0.3, 1]}}}


TOKENS = _load_tokens()


_RESOLVE = None


def get_resolve():
    """Return the Resolve object (works inside Resolve's console, MCP servers and external Python).
    Pass your own with use_resolve(resolve) if the host already gives you one."""
    if _RESOLVE is not None:
        return _RESOLVE
    g = globals()
    if "resolve" in g and g["resolve"]:
        return g["resolve"]
    try:
        import DaVinciResolveScript as dvr  # noqa: N813
    except ImportError:
        paths = {
            "darwin": "/Library/Application Support/Blackmagic Design/DaVinci Resolve/Developer/Scripting/Modules",
            "win32": os.path.join(os.environ.get("PROGRAMDATA", "C:\\ProgramData"), "Blackmagic Design", "DaVinci Resolve", "Support", "Developer", "Scripting", "Modules"),
            "linux": "/opt/resolve/Developer/Scripting/Modules",
        }
        sys.path.append(paths.get(sys.platform, paths["linux"]))
        import DaVinciResolveScript as dvr  # noqa: N813
    r = dvr.scriptapp("Resolve")
    if not r:
        raise RuntimeError("Could not connect to DaVinci Resolve. Is it running with external scripting enabled?")
    return r


def use_resolve(resolve_obj):
    """Use the Resolve object your host already has (e.g. the MCP's `resolve`)."""
    global _RESOLVE
    _RESOLVE = resolve_obj


def _hex(c):
    h = c.lstrip("#")
    v = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    return v + [int(h[6:8], 16) / 255 if len(h) >= 8 else 1.0]


def _media_index(items):
    out = {}
    for it in items or []:
        try:
            out[os.path.normcase(os.path.abspath(it.GetClipProperty("File Path")))] = it
        except Exception:
            pass
    return out


def assemble(pkg_dir, timeline_name=None, project_name=None):
    """Build a timeline from pkg/manifest.json. Returns a short report."""
    m = json.load(open(os.path.join(pkg_dir, "manifest.json")))
    fps = m["fps"]
    resolve = get_resolve()
    pm = resolve.GetProjectManager()
    project = pm.GetCurrentProject()
    if project is None or project_name:
        project = pm.CreateProject(project_name or m["name"]) or pm.GetCurrentProject()
    mp = project.GetMediaPool()
    root = mp.GetRootFolder()
    folder = mp.AddSubFolder(root, "Ink & Signal - " + m["name"]) or root
    mp.SetCurrentFolder(folder)
    files = []
    for tr in ("V1", "V2", "V3", "A1", "A2"):
        for it in m["tracks"].get(tr, []):
            if it["file"] not in files and os.path.exists(it["file"]):
                files.append(it["file"])
    items = _media_index(mp.ImportMedia(files))
    # project settings only stick before the first timeline; per-timeline custom settings otherwise
    for k, v in (("timelineFrameRate", str(fps)), ("timelineResolutionWidth", str(m["width"])), ("timelineResolutionHeight", str(m["height"]))):
        try:
            project.SetSetting(k, v)
        except Exception:
            pass
    tl = mp.CreateEmptyTimeline(timeline_name or m["name"])
    project.SetCurrentTimeline(tl)
    for k, v in (("useCustomSettings", "1"), ("timelineFrameRate", str(fps)), ("timelineResolutionWidth", str(m["width"])), ("timelineResolutionHeight", str(m["height"]))):
        try:
            tl.SetSetting(k, v)
        except Exception:
            pass
    while tl.GetTrackCount("video") < 3:
        tl.AddTrack("video")
    while tl.GetTrackCount("audio") < 2:
        tl.AddTrack("audio", "stereo")
    t0 = tl.GetStartFrame()
    placed, missing = 0, []

    def put(it, track_index, media_type):
        nonlocal placed
        mpi = items.get(os.path.normcase(os.path.abspath(it["file"])))
        if mpi is None:
            missing.append(it["file"])
            return
        src_in = int(it.get("srcInFrames") or 0)
        n = int(it["end"] - it["start"])
        info = {"mediaPoolItem": mpi, "startFrame": src_in, "endFrame": src_in + n - 1,
                "trackIndex": track_index, "recordFrame": t0 + int(it["start"]), "mediaType": media_type}
        if mp.AppendToTimeline([info]):
            placed += 1

    for it in m["tracks"]["V1"]:
        put(it, 1, 1)
    for it in m["tracks"]["V2"]:
        put(it, 2, 1)
    for it in m["tracks"]["V3"]:
        put(it, 3, 1)
    for it in m["tracks"].get("A1", []):
        put(it, 1, 2)
    for it in m["tracks"].get("A2", []):
        put(it, 2, 2)
    for mk in m.get("markers", []):
        try:
            tl.AddMarker(int(mk["frame"]), "Red", mk["label"][:60], "Ink & Signal", 1)
        except Exception:
            pass
    report = f"Ink & Signal: placed {placed} items on '{tl.GetName()}'" + (f"; missing: {missing}" if missing else "")
    print(report)
    return report


def add_title(text, at_frame=None, duration=75, size_px=None, color="signal", font="display", y=0.5):
    """(beta) Insert a native Fusion Text+ title at the playhead (or at_frame), styled with Ink & Signal tokens,
    with the 'land' move: size 112% → 100% over 12 frames using the snap curve.
    Text+ stays editable in Resolve's Inspector. The selection box and handles are not built natively here;
    use the rendered ov-title overlay from the package for those."""
    resolve = get_resolve()
    tl = resolve.GetProjectManager().GetCurrentProject().GetCurrentTimeline()
    if at_frame is not None:
        try:
            fps = float(tl.GetSetting("timelineFrameRate"))
            f = int(tl.GetStartFrame() + at_frame)
            s = f / fps
            tl.SetCurrentTimecode("%02d:%02d:%02d:%02d" % (s // 3600, (s // 60) % 60, s % 60, f % round(fps)))
        except Exception:
            pass
    item = tl.InsertFusionTitleIntoTimeline("Text+")
    if not item:
        raise RuntimeError("Could not insert a Text+ title (select a video track and place the playhead).")
    comp = item.GetFusionCompByIndex(1)
    tool = comp.FindToolByID("TextPlus") if hasattr(comp, "FindToolByID") else None
    if tool is None:
        tools = comp.GetToolList(False, "TextPlus")
        tool = list(tools.values())[0] if tools else None
    f = TOKENS["font"][font]
    tool.SetInput("StyledText", str(text).upper() if f.get("case") == "upper" else str(text))
    tool.SetInput("Font", f["family"])
    tool.SetInput("Style", f["style"])
    r, g, b, a = _hex(TOKENS["color"].get(color, color))
    for k, v in (("Red1", r), ("Green1", g), ("Blue1", b), ("Alpha1", a)):
        tool.SetInput(k, v)
    tool.SetInput("CharacterSpacing", 1.0 + float(f.get("tracking", 0)))
    tool.SetInput("Center", {1: 0.5, 2: 1 - y})
    height = float(tl.GetSetting("timelineResolutionHeight") or 1920)
    base = (size_px or 200) / height * 1.18  # Text+ size is relative to frame height; 1.18 maps cap-height → em
    try:
        tool.AddModifier("Size", "BezierSpline")
        tool.SetInput("Size", base * 1.12, 4)
        tool.SetInput("Size", base, 16)
        spline = tool.Size.GetConnectedOutput().GetTool()
        x1, y1, x2, y2 = TOKENS["ease"]["snap"]["bezier"]
        v0, v1 = base * 1.12, base
        spline.SetKeyFrames({
            4.0: {1: v0, "RH": {1: 4 + x1 * 12, 2: v0 + y1 * (v1 - v0)}},
            16.0: {1: v1, "LH": {1: 4 + x2 * 12, 2: v0 + y2 * (v1 - v0)}},
        }, True)
    except Exception:
        tool.SetInput("Size", base)
    try:
        item.SetProperty("Duration", duration)
    except Exception:
        pass
    return "Text+ title inserted: " + str(text)


if __name__ == "__main__" and "__file__" in globals() and os.path.basename(sys.argv[0] or "") == os.path.basename(__file__):
    if len(sys.argv) < 2:
        sys.exit("usage: python3 ink_signal_resolve.py /path/to/pkg")
    assemble(sys.argv[1])
