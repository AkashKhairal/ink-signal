/*
 * Ink & Signal — Premiere Pro adapter (ExtendScript / ES3, CEP bridge)
 * ---------------------------------------------------------------------
 * Assembles an Ink & Signal NLE package into a Premiere sequence:
 *   V1 picture (your clips + full-frame Ink & Signal comps)
 *   V2 overlays (captions, lower thirds, chips, titles — ProRes 4444 with alpha)
 *   V3 transitions (torn wipes, flashes, paper roll — cut sits under the covered frames)
 *   A1 clip audio, A2 music · sequence markers from the plan
 *
 * Make the package first:   node render/nle.mjs plan.json --out pkg
 * No-script route:          File › Import… › pkg/timeline.xml   (FCP7 XML)
 * Scripted / MCP route:     run this file, then  InkSignalPPro.assemble("/abs/path/pkg")
 *   e.g. with a Premiere MCP that exposes execute_extendscript:
 *   $.evalFile("/abs/path/ink-signal/integrations/premiere-pro/InkSignal.premiere.jsx"); InkSignalPPro.assemble("/abs/path/pkg");
 * MCPs without script execution: use their import_media + add_to_timeline tools with the values in pkg/manifest.json
 * (file, track, startSec, srcInFrames / fps, endSec) — see integrations/premiere-pro/README.md.
 */
var InkSignalPPro = (function () {
  var P = { version: '2.0.0' };

  function readText(path) { var f = new File(path); f.encoding = 'UTF-8'; if (!f.exists) throw new Error('Ink & Signal: missing ' + path); f.open('r'); var s = f.read(); f.close(); return s; }
  function parseJSON(s) { return eval('(' + s + ')'); } // manifest is generated by ink-signal (trusted)
  function norm(p) { return String(p).replace(/\\/g, '/').toLowerCase(); }

  function findItemByPath(bin, path) {
    var target = norm(path);
    for (var i = 0; i < bin.children.numItems; i++) {
      var it = bin.children[i];
      if (it.type === ProjectItemType.BIN) { var r = findItemByPath(it, path); if (r) return r; }
      else { try { if (norm(it.getMediaPath()) === target) return it; } catch (e) {} }
    }
    return null;
  }
  function findBin(name) {
    var root = app.project.rootItem;
    for (var i = 0; i < root.children.numItems; i++) if (root.children[i].type === ProjectItemType.BIN && root.children[i].name === name) return root.children[i];
    return root.createBin(name);
  }
  function importAll(paths, bin) {
    var todo = [];
    for (var i = 0; i < paths.length; i++) if (!findItemByPath(app.project.rootItem, paths[i]) && new File(paths[i]).exists) todo.push(paths[i]);
    if (todo.length) app.project.importFiles(todo, true, bin, false);
  }
  function trackFor(seq, kind, idx) {
    var tracks = kind === 'video' ? seq.videoTracks : seq.audioTracks;
    if (tracks.numTracks <= idx) {
      try { app.enableQE(); var q = qe.project.getActiveSequence(); if (kind === 'video') q.addTracks(idx - tracks.numTracks + 1, tracks.numTracks, 0); else q.addTracks(0, 0, idx - tracks.numTracks + 1); } catch (e) {}
      tracks = kind === 'video' ? seq.videoTracks : seq.audioTracks;
    }
    return tracks[idx];
  }

  /** assemble pkg/manifest.json into a new sequence */
  P.assemble = function (pkgDir, opts) {
    opts = opts || {};
    var m = parseJSON(readText(pkgDir + '/manifest.json'));
    var fps = m.fps, bin = findBin('Ink & Signal — ' + m.name);
    var all = [], k, i, t, keys = ['V1', 'V2', 'V3', 'A1', 'A2'];
    for (k = 0; k < keys.length; k++) for (i = 0; i < (m.tracks[keys[k]] || []).length; i++) all.push(m.tracks[keys[k]][i].file);
    importAll(all, bin);
    // sequence settings from a full-frame render (or the first clip) so size and fps match
    var ref = null;
    for (i = 0; i < m.tracks.V1.length && !ref; i++) if (m.tracks.V1[i].kind === 'comp') ref = findItemByPath(app.project.rootItem, m.tracks.V1[i].file);
    if (!ref) ref = findItemByPath(app.project.rootItem, m.tracks.V1[0].file);
    var seq = app.project.createNewSequenceFromClips(opts.name || m.name, [ref], bin);
    // clear what createNewSequenceFromClips placed
    for (t = 0; t < seq.videoTracks.numTracks; t++) while (seq.videoTracks[t].clips.numItems) seq.videoTracks[t].clips[0].remove(false, false);
    for (t = 0; t < seq.audioTracks.numTracks; t++) while (seq.audioTracks[t].clips.numItems) seq.audioTracks[t].clips[0].remove(false, false);
    var placed = 0, missing = [];
    var place = function (it, kind, idx, mediaTypeForInOut) {
      var pi = findItemByPath(app.project.rootItem, it.file);
      if (!pi) { missing.push(it.file); return; }
      var srcIn = (it.srcInFrames || 0) / fps, dur = (it.end - it.start) / fps;
      try { pi.setInPoint(srcIn, mediaTypeForInOut); pi.setOutPoint(srcIn + dur, mediaTypeForInOut); } catch (e) {}
      trackFor(seq, kind, idx).overwriteClip(pi, it.start / fps);
      try { pi.clearInPoint(); pi.clearOutPoint(); } catch (e2) {}
      placed++;
    };
    // pictures and overlays: video only (mediaType 1) so audio is placed explicitly below
    for (i = 0; i < m.tracks.V1.length; i++) place(m.tracks.V1[i], 'video', 0, 4);
    for (i = 0; i < m.tracks.V2.length; i++) place(m.tracks.V2[i], 'video', 1, 4);
    for (i = 0; i < m.tracks.V3.length; i++) place(m.tracks.V3[i], 'video', 2, 4);
    for (i = 0; i < (m.tracks.A2 || []).length; i++) place(m.tracks.A2[i], 'audio', 1, 4);
    for (i = 0; i < (m.markers || []).length; i++) { var mk = seq.markers.createMarker(m.markers[i].frame / fps); mk.name = m.markers[i].label; }
    return 'Ink & Signal: placed ' + placed + ' items in "' + seq.name + '"' + (missing.length ? '; missing: ' + missing.join(', ') : '');
  };

  /** place one rendered overlay (e.g. a lower third .mov) on V2 at the playhead of the active sequence */
  P.placeOverlay = function (file, trackIndex) {
    var seq = app.project.activeSequence; if (!seq) throw new Error('Open a sequence');
    importAll([file], findBin('Ink & Signal — overlays'));
    var pi = findItemByPath(app.project.rootItem, file);
    trackFor(seq, 'video', trackIndex == null ? 1 : trackIndex).overwriteClip(pi, seq.getPlayerPosition().seconds);
    return 'placed ' + pi.name;
  };

  return P;
})();
