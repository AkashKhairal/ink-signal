#!/usr/bin/env node
// Writes docs/CATALOG.md from the registries: every IS Spec comp and every motion scene, with formats and params.
//   node tools/catalog.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { COMPS } = await import(path.join(ROOT, 'runtime/comps/index.js'));
const { SCENES } = await import(path.join(ROOT, 'runtime/motion/scenes/index.js'));
const { sceneFrames } = await import(path.join(ROOT, 'runtime/motion/scene.js'));

const short = (v) => { const s = JSON.stringify(v); return s.length > 90 ? s.slice(0, 87) + '…' : s; };
const params = (d) => Object.entries(d || {}).filter(([k]) => !k.startsWith('__')).map(([k, v]) => `\`${k}\`=${short(v)}`).join(' · ');
const groups = [
  ['Explainers', (d) => d.kind === 'explainer'],
  ['Screen recordings', (d) => d.kind === 'screen'],
  ['Motion B-roll', (d) => d.kind === 'broll'],
  ['Infographics', (d) => d.kind === 'infographic'],
  ['Cards', (d) => d.kind === 'card'],
  ['Kinetic titles', (d) => d.kind === 'title'],
  ['Transitions (motion)', (d) => d.kind === 'transition'],
];
let md = `# Catalog\n\nGenerated by \`node tools/catalog.mjs\`. Two engines, one plan format:\n\n- **IS Spec comps** (canvas renderer, rebuilt natively in After Effects): titles, A-roll overlays, captions, transitions, 3D.\n- **Signal Motion scenes** (browser engine: springs, camera, cursor, UI kit, charts): explainers, B-roll, infographics, cards, kinetic titles, object transitions. Delivered to editors as rendered ProRes (4444 with alpha for overlays).\n\nAny name below works in \`node render/cli.mjs render <name> --format reel|yt|square --params '{…}' --out file\` and as \`"comp"\` in an edit plan.\n\n`;
md += `## IS Spec comps (${Object.keys(COMPS).length})\n\n| Name | Kind | Formats | What it does |\n|---|---|---|---|\n`;
for (const [k, d] of Object.entries(COMPS)) md += `| \`${k}\` | ${d.kind} | ${d.formats.join(', ')} | ${d.description} |\n`;
md += `\n## Signal Motion scenes (${Object.keys(SCENES).length})\n`;
for (const [g, f] of groups) {
  const list = Object.values(SCENES).filter(f);
  if (!list.length) continue;
  md += `\n### ${g}\n\n`;
  for (const d of list) {
    const { frames, fps } = sceneFrames(d, {});
    md += `#### \`${d.name}\` — ${d.title}\n${d.description}\n\n- Formats: ${d.formats.join(', ')} · default theme: ${d.theme}${d.transparent ? ' · transparent' : ''}${d.loop ? ' · loops' : ''} · default length ${(frames / fps).toFixed(1)} s\n- Params: ${params(d.defaults)}\n\n`;
  }
}
fs.writeFileSync(path.join(ROOT, 'docs', 'CATALOG.md'), md);
console.log(`docs/CATALOG.md — ${Object.keys(COMPS).length} comps, ${Object.keys(SCENES).length} motion scenes`);
