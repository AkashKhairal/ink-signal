"""Build derived files from the single source of truth.

    python3 tools/build.py

Reads  tokens/ink-signal.tokens.json and fonts/*.ttf
Writes runtime/tokens.js      (ES module, used by the web runtime and Node exporters)
       runtime/metrics.js     (font metrics so layouts are identical in browser, Node, AE and Resolve)
       tokens/tokens.css      (CSS custom properties + @font-face)
       integrations/davinci-resolve/ink_signal_tokens.py (tokens as a Python dict)
"""
import json, os, sys
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = json.load(open(os.path.join(ROOT, "tokens", "ink-signal.tokens.json")))

CHARS = [chr(c) for c in range(32, 127)] + [chr(c) for c in range(0xA0, 0x100)] + list("·×—–’‘“”•…₹€→←↑↓↘↗✓′″")

def metrics(path):
    f = TTFont(path); cmap = f.getBestCmap(); hmtx = f["hmtx"]; os2 = f["OS/2"]; hhea = f["hhea"]
    adv = {}
    for ch in CHARS:
        gn = cmap.get(ord(ch))
        if gn: adv[ch] = hmtx[gn][0]
    return {
        "upm": f["head"].unitsPerEm,
        "ascender": hhea.ascent, "descender": hhea.descent,
        "capHeight": getattr(os2, "sCapHeight", 700) or 700,
        "xHeight": getattr(os2, "sxHeight", 500) or 500,
        "fallback": round(sum(adv.values()) / max(1, len(adv))),
        "adv": adv,
    }

def main():
    fonts = {k: v for k, v in T["font"].items() if isinstance(v, dict)}
    M = {}
    for key, spec in fonts.items():
        M[key] = metrics(os.path.join(ROOT, spec["file"]))
        M[key]["postscript"] = spec["postscript"]
    with open(os.path.join(ROOT, "runtime", "metrics.js"), "w") as fh:
        fh.write("// GENERATED by tools/build.py from fonts/*.ttf. Do not edit.\n")
        fh.write("export default " + json.dumps(M, ensure_ascii=False, separators=(",", ":")) + ";\n")
    with open(os.path.join(ROOT, "runtime", "tokens.js"), "w") as fh:
        fh.write("// GENERATED by tools/build.py from tokens/ink-signal.tokens.json. Do not edit.\n")
        fh.write("export default " + json.dumps(T, ensure_ascii=False, indent=1) + ";\n")
    # CSS
    c = T["color"]
    lines = ["/* GENERATED by tools/build.py. Ink & Signal tokens as CSS custom properties. */"]
    for key, spec in fonts.items():
        lines.append("@font-face{font-family:'IS %s';src:url('../%s') format('truetype');font-display:block}" % (key, spec["file"]))
    lines.append(":root{")
    for k, v in c.items():
        if isinstance(v, str): lines.append("  --is-%s:%s;" % (k, v))
    for k, v in T["ease"].items():
        if v["bezier"]: lines.append("  --is-ease-%s:cubic-bezier(%s);" % (k, ",".join(str(x) for x in v["bezier"])))
    for key in fonts: lines.append("  --is-font-%s:'IS %s';" % (key, key))
    lines.append("}")
    open(os.path.join(ROOT, "tokens", "tokens.css"), "w").write("\n".join(lines) + "\n")
    # Python tokens for Resolve
    with open(os.path.join(ROOT, "integrations", "davinci-resolve", "ink_signal_tokens.py"), "w") as fh:
        fh.write("# GENERATED by tools/build.py from tokens/ink-signal.tokens.json. Do not edit.\n")
        import pprint
        fh.write("TOKENS = " + pprint.pformat(T, width=110, sort_dicts=False) + "\n")
    print("built: runtime/tokens.js runtime/metrics.js tokens/tokens.css integrations/davinci-resolve/ink_signal_tokens.py")

if __name__ == "__main__":
    main()
